WEEKDAY_NAMES = (
    "понедельник",
    "вторник",
    "среда",
    "четверг",
    "пятница",
    "суббота",
    "воскресенье",
)

MONTH_LENGTHS = (31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31)


# --------------------------------------------------------------------------- #
#                             Логика приложения                                #
# --------------------------------------------------------------------------- #

def is_leap_year(year: int) -> bool:
    """Возвращает True, если год високосный по правилам григорианского календаря.

    Год високосный, если он делится на 4, но не делится на 100,
    либо делится на 400.

    >>> is_leap_year(2000), is_leap_year(1900), is_leap_year(2024)
    (True, False, True)
    """
    return year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)


def days_in_month(month: int, year: int) -> int:
    """Число дней в месяце с учётом високосного года."""
    if month == 2 and is_leap_year(year):
        return 29
    return MONTH_LENGTHS[month - 1]


def weekday_name(day: int, month: int, year: int) -> str:
    """Определяет день недели по дате при помощи конгруэнции Зеллера.

    Алгоритм не использует стандартную библиотеку дат, вычисление
    выполняется арифметически.

    >>> weekday_name(12, 4, 1961)   # полёт Гагарина — среда
    'среда'
    """
    q = day
    m = month
    y = year
    # Январь и февраль в алгоритме Зеллера считаются 13-м и 14-м месяцами
    # предыдущего года.
    if m < 3:
        m += 12
        y -= 1
    k = y % 100          # год внутри столетия
    j = y // 100         # номер столетия
    h = (q + (13 * (m + 1)) // 5 + k + k // 4 + j // 4 + 5 * j) % 7
    # h: 0 — суббота, 1 — воскресенье, 2 — понедельник, ...
    # приводим к индексу списка, где 0 — понедельник
    return WEEKDAY_NAMES[(h + 5) % 7]


def calculate_age(day: int, month: int, year: int, today: date | None = None) -> int:
    """Возвращает полное количество лет на указанную (по умолчанию текущую) дату.

    >>> calculate_age(1, 6, 2000, today=date(2024, 5, 31))
    23
    >>> calculate_age(1, 6, 2000, today=date(2024, 6, 1))
    24
    """
    if today is None:
        today = date.today()
    age = today.year - year
    # День рождения в этом году ещё не наступил — вычитаем один год.
    if (today.month, today.day) < (month, day):
        age -= 1
    return age


def render_number(text: str) -> str:
    """Собирает многострочное изображение строки из цифр и пробелов.

    >>> print(render_number("1"))
      *
     **
      *
      *
      *
      *
     ***
    """
    rows = [""] * DIGIT_HEIGHT
    for position, char in enumerate(text):
        glyph = DIGIT_FONT.get(char, DIGIT_FONT[" "])
        for row_index in range(DIGIT_HEIGHT):
            separator = " " if position else ""
            rows[row_index] += separator + glyph[row_index]
    return "\n".join(row.rstrip() for row in rows)


def format_date_as_display(day: int, month: int, year: int) -> str:
    """Готовит строку "дд мм гггг" и прорисовывает её звёздочками."""
    return render_number(f"{day:02d} {month:02d} {year:04d}")


# --------------------------------------------------------------------------- #
#                            Ввод и валидация                                  #
# --------------------------------------------------------------------------- #

def ask_int(prompt: str, minimum: int, maximum: int) -> int:
    """Запрашивает целое число в заданном диапазоне, пока ввод не станет корректным."""
    while True:
        raw = input(prompt).strip()
        try:
            value = int(raw)
        except ValueError:
            print("  Ошибка: нужно ввести целое число.")
            continue
        if not minimum <= value <= maximum:
            print(f"  Ошибка: значение должно быть от {minimum} до {maximum}.")
            continue
        return value


def read_birth_date() -> tuple[int, int, int]:
    """Последовательно запрашивает день, месяц и год рождения с проверкой корректности."""
    today = date.today()
    while True:
        day = ask_int("Введите день рождения (1-31): ", 1, 31)
        month = ask_int("Введите месяц рождения (1-12): ", 1, 12)
        year = ask_int(f"Введите год рождения (1900-{today.year}): ", 1900, today.year)

        # Несуществующее число месяца — переспрашиваем только день.
        while day > days_in_month(month, year):
            print(
                f"  Ошибка: в месяце {month:02d}.{year} только "
                f"{days_in_month(month, year)} дней."
            )
            day = ask_int("Введите день рождения заново: ", 1, days_in_month(month, year))

        if (year, month, day) > (today.year, today.month, today.day):
            print("  Ошибка: дата рождения не может быть в будущем. Повторите ввод.\n")
            continue
        return day, month, year


# --------------------------------------------------------------------------- #
#                                  Точка входа                                 #
# --------------------------------------------------------------------------- #

def main() -> None:
    print("=" * 52)
    print("  Информация о дате рождения".center(52))
    print("=" * 52)

    day, month, year = read_birth_date()

    print("\n" + "-" * 52)
    print(f"Дата рождения:   {day:02d}.{month:02d}.{year}")
    print(f"День недели:     {weekday_name(day, month, year)}")
    print(f"Високосный год:  {'да' if is_leap_year(year) else 'нет'}")
    print(f"Полных лет:      {calculate_age(day, month, year)}")
    print("-" * 52 + "\n")

    print(format_date_as_display(day, month, year))
    print()


if __name__ == "__main__":
    main()
