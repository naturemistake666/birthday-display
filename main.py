"""
Кейс-задача № 1. Стилистическое преобразование чисел.

Программа последовательно запрашивает у пользователя день, месяц и год рождения,
после чего:
  * определяет день недели, на который выпала эта дата (алгоритм Зеллера);
  * определяет, был ли год високосным (григорианский календарь);
  * вычисляет полное количество лет пользователя на текущую дату;
  * выводит дату рождения в формате "дд мм гггг", где цифры прорисованы
    символами '*' — имитация электронного табло.

Запуск:  python main.py
"""

# Отложенное вычисление аннотаций: позволяет пользоваться синтаксисом "date | None"
# (PEP 604) на интерпретаторах старше 3.10 — например на системном Python 3.9.
