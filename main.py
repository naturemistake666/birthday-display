# Кейс-задача № 1. Стилистическое преобразование чисел.
#
# Программа спрашивает у пользователя день, месяц и год рождения, а потом:
#   - определяет день недели этой даты;
#   - определяет, был ли год високосным;
#   - считает, сколько пользователю сейчас полных лет;
#   - выводит дату в виде "дд мм гггг", где цифры нарисованы звёздочками.
#
# Запуск: python main.py

