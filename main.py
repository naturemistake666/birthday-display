# Названия дней недели. Первый элемент - понедельник.
WEEKDAY_NAMES = ["понедельник", "вторник", "среда", "четверг",
                 "пятница", "суббота", "воскресенье"]

# Сколько дней в каждом месяце обычного года (январь - декабрь).
MONTH_LENGTHS = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]


# ------------------------------------------------------------------
# Функции по условию задачи
# ------------------------------------------------------------------

def is_leap_year(year):
    """Проверяет, високосный ли год."""
    # Год високосный, если делится на 4,
    # но годы, кратные 100, високосными не считаются,
    # кроме тех, что делятся ещё и на 400.
    if year % 400 == 0:
        return True
    if year % 100 == 0:
        return False
    if year % 4 == 0:
        return True
    return False


def days_in_month(month, year):
    """Возвращает количество дней в месяце."""
    # В феврале високосного года 29 дней вместо 28.
    if month == 2 and is_leap_year(year):
        return 29
    return MONTH_LENGTHS[month - 1]


def weekday_name(day, month, year):
    """Определяет день недели по формуле Зеллера."""
    d = day
    m = month
    y = year

    # В формуле Зеллера январь и февраль считаются 13-м и 14-м
    # месяцами предыдущего года.
    if m < 3:
        m = m + 12
        y = y - 1

    k = y % 100          # две последние цифры года
    j = y // 100         # столетие

    h = (d + (13 * (m + 1)) // 5 + k + k // 4 + j // 4 + 5 * j) % 7

    # В формуле h = 0 это суббота, h = 1 воскресенье, h = 2 понедельник.
    # В нашем списке первый день - понедельник, поэтому сдвигаем номер.
    number = (h + 5) % 7
    return WEEKDAY_NAMES[number]


def calculate_age(day, month, year, today=None):
    """Считает, сколько полных лет человеку."""
    if today is None:
        today = date.today()

    age = today.year - year

    # Если день рождения в этом году ещё не наступил,
    # то полных лет на один меньше.
    if today.month < month:
        age = age - 1
    elif today.month == month and today.day < day:
        age = age - 1

    return age


# ------------------------------------------------------------------
# Вывод даты звёздочками
# ------------------------------------------------------------------

def render_number(text):
    """Рисует строку из цифр и пробелов символами '*'."""
    # Готовим 7 пустых строк - будущие строки табло.
    rows = []
    for i in range(DIGIT_HEIGHT):
        rows.append("")

    # Идём по символам и дописываем каждую цифру справа.
    for position in range(len(text)):
        char = text[position]

        if char in DIGIT_FONT:
            glyph = DIGIT_FONT[char]
        else:
            glyph = DIGIT_FONT[" "]

        for i in range(DIGIT_HEIGHT):
            if position > 0:
                # Отделяем цифру от предыдущей одним пробелом.
                rows[i] = rows[i] + " " + glyph[i]
            else:
                rows[i] = rows[i] + glyph[i]

    # Убираем лишние пробелы справа и склеиваем строки.
    result = []
    for i in range(DIGIT_HEIGHT):
        result.append(rows[i].rstrip())

    return "\n".join(result)


def format_date_as_display(day, month, year):
    """Собирает строку "дд мм гггг" и рисует её звёздочками."""
    text = f"{day:02d} {month:02d} {year:04d}"
    return render_number(text)


# ------------------------------------------------------------------
# Ввод данных с проверкой
# ------------------------------------------------------------------

def ask_int(question, minimum, maximum):
    """Спрашивает целое число, пока не введут правильное."""
    while True:
        answer = input(question)

        try:
            number = int(answer)
        except ValueError:
            print("Ошибка: нужно ввести целое число.")
            continue

        if number < minimum or number > maximum:
            print(f"Ошибка: число должно быть от {minimum} до {maximum}.")
            continue

        return number


def read_birth_date():
    """Спрашивает день, месяц и год рождения."""
    today = date.today()

    while True:
        day = ask_int("Введите день рождения (1-31): ", 1, 31)
        month = ask_int("Введите месяц рождения (1-12): ", 1, 12)
        year = ask_int(f"Введите год рождения (1900-{today.year}): ", 1900, today.year)

        # Проверяем, что такой день в этом месяце существует.
        max_day = days_in_month(month, year)
        while day > max_day:
            print(f"Ошибка: в месяце {month} {year} года только {max_day} дней.")
            day = ask_int("Введите день рождения заново: ", 1, max_day)

        # Дата рождения не может быть позже сегодняшнего дня.
        if year == today.year:
            if month > today.month or (month == today.month and day > today.day):
                print("Ошибка: дата рождения не может быть в будущем.")
                continue

        return day, month, year


# ------------------------------------------------------------------
# Основная программа
# ------------------------------------------------------------------

def main():
    day, month, year = read_birth_date()

    print()
    print("Дата рождения:", f"{day:02d}.{month:02d}.{year}")
    print("День недели:", weekday_name(day, month, year))

    if is_leap_year(year):
        print("Високосный год: да")
    else:
        print("Високосный год: нет")

    print("Полных лет:", calculate_age(day, month, year))
    print()
    print(format_date_as_display(day, month, year))


